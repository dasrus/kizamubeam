export function t(de: string, vars?: Record<string, string | number>): string {
  // English and Russian are translated here; other languages get the English texts, as in the app
  let s = lang === 'de' ? de : lang === 'ru' ? (RU[de] ?? EN[de] ?? de) : (EN[de] ?? de);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
